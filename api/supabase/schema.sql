-- Gundam Nexus - skema database (jalankan di Supabase > SQL Editor > New query)
-- Jalankan seluruh blok sekaligus karena mobile_suits bergantung pada series.

create table if not exists series (
  id          integer generated by default as identity primary key,
  slug        text unique not null,
  name        text not null,
  year        integer not null,
  timeline    text,
  format      text,
  color       text default '#35d4ff',
  synopsis    text,
  image_url   text,
  created_at  timestamptz default now()
);

create table if not exists mobile_suits (
  id            integer generated by default as identity primary key,
  name          text not null,
  model_number  text not null,
  series_id     integer not null references series(id) on delete cascade,
  pilot         text,
  faction       text,
  unit_type     text,
  height_m      numeric(6,2),
  weight_t      numeric(7,2),
  armaments     text[] not null default '{}',
  description   text,
  image_url     text,
  created_at    timestamptz default now()
);

create index if not exists mobile_suits_series_id_idx on mobile_suits(series_id);

